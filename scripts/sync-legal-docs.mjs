#!/usr/bin/env node
// Copy the Markdown sources of the public legal and explainer pages (docs/legal/*.md,
// docs/bluetooth-mesh.md) into src/portal/legal/documents.ts, which the portal renders. The
// server image does not ship docs/, so the text is compiled in. Run after editing a source:
//   node scripts/sync-legal-docs.mjs
// tests/portal/legal-pages.test.ts fails when the two drift.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCES = {
  terms: "docs/legal/terms.md",
  privacy: "docs/legal/privacy.md",
  "acceptable-use": "docs/legal/acceptable-use.md",
  "host-agreement": "docs/legal/host-agreement.md",
  bluetooth: "docs/bluetooth-mesh.md"
};

const body = Object.entries(SOURCES)
  .map(([key, path]) => `  ${JSON.stringify(key)}: ${JSON.stringify(readFileSync(join(root, path), "utf8"))}`)
  .join(",\n");
const out = `// Copyright (c) 2025 EdgeCoder
// SPDX-License-Identifier: BUSL-1.1

// GENERATED by scripts/sync-legal-docs.mjs from ${Object.values(SOURCES).join(", ")}. Do not edit:
// edit the Markdown and re-run the script.
export const PUBLIC_DOCUMENTS = {
${body}
} as const;

export type PublicDocumentKey = keyof typeof PUBLIC_DOCUMENTS;
export const PUBLIC_DOCUMENT_SOURCES: Record<PublicDocumentKey, string> = ${JSON.stringify(SOURCES)};
`;
writeFileSync(join(root, "src/portal/legal/documents.ts"), out);
console.log("sync-legal-docs: wrote src/portal/legal/documents.ts");
