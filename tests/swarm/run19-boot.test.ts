describe("run 19, outage 3b: an agent that went home tells the peer", () => {
  const iad = createPeerKeys("agent-run19-iad");
  const lax = createPeerKeys("agent-run19-lax");

  test("after the leaving pull, the peer neither holds a call for it nor counts it ready; the call goes to a host still here", async () => {
    for (const k of [lhr, fra]) expect((await pull(k, 1, 0)).id).toBeNull();
    await register(iad, "token-host", { installedModels: [MODEL], region: "iad" });
    await register(lax, "token-host", { installedModels: [MODEL], region: "lax" });
    for (const k of [iad, lax]) expect((await pull(k, 1)).id).toBeNull();
    // iad goes home: its last pull here reports no free slot and takes no nudges.
    const left = await post("/pull", leavingPullBody({ agentId: iad.peerId, slots: 1, contextWindow: 32768 }), iad);
    expect(left.statusCode, left.body).toBe(200);
    expect(left.json().subtask ?? null).toBeNull();
    const c = await submit({ model: MODEL, clientRegion: "iad" });
    expect(c.r.statusCode, c.r.body).toBe(200);
    // Was: preferred iad (nearest, "ready"), refused at the bound.
    expect(dispatch.preferredAgentFor(c.subtaskId)).toBe(lax.peerId);
    const cands = dispatch.claimCandidates(ctx.queue.getSubtask(c.subtaskId));
    expect(cands.ready).not.toContain(iad.peerId);
    expect(cands.not[iad.peerId]).toBe("reported_full");
    expect((await pull(lax, 1)).id).toBe(c.subtaskId);
    await finish(lax, c.taskId, c.subtaskId);
    await post("/pull", { agentId: lax.peerId, inferenceSlots: 1, freeInferenceSlots: 0 }, lax);
  });

  test("leavingPullBody: no free slot, no nudges, its slot count kept", () => {
    expect(leavingPullBody({ agentId: "a", slots: 2, contextWindow: 8192 })).toEqual({ agentId: "a", inferenceSlots: 2, freeInferenceSlots: 0, wake: false, contextWindow: 8192 });
    expect(leavingPullBody({ agentId: "a", slots: 0 })).toEqual({ agentId: "a", inferenceSlots: 1, freeInferenceSlots: 0, wake: false });
  });
});
