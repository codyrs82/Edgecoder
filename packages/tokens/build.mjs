// Generates dist/tokens.css from src/tokens.json (#23).
// Light is the :root default; dark applies via [data-theme=dark] or, when no
// explicit choice is made, via prefers-color-scheme. `--check` fails if dist is stale.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

export function buildCss(tokens) {
  const mode = (m) =>
    Object.entries(tokens.color).map(([k, v]) => `  --${k}: ${v[m]};`).join("\n");
  const shared = [
    ...Object.entries(tokens.space).map(([k, v]) => `  --space-${k}: ${v};`),
    ...Object.entries(tokens.radius).map(([k, v]) => `  --radius-${k}: ${v};`),
    ...Object.entries(tokens.font).map(([k, v]) => `  --font-${k}: ${v};`),
    "  /* Portal-compatible aliases — keeps portal-authored CSS working unchanged */",
    ...Object.entries(tokens.aliases).map(([k, v]) => `  --${k}: var(--${v});`)
  ].join("\n");
  return `/* GENERATED by packages/tokens/build.mjs from src/tokens.json — do not edit. */
:root {
${shared}
}
:root {
  color-scheme: light;
${mode("light")}
}
[data-theme=dark] {
  color-scheme: dark;
${mode("dark")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme=light]) {
    color-scheme: dark;
${mode("dark").replace(/^/gm, "  ")}
  }
}
`;
}

// Tailwind v4 @theme mapping. Colors/spacing point at the runtime vars so the
// light/dark switch applies to utilities; radius/font share names with the
// runtime vars, so they get literal values (a self-referencing var() would cycle).
export function buildTheme(tokens) {
  const lines = [
    ...Object.keys(tokens.color).map((k) => `  --color-${k}: var(--${k});`),
    ...Object.keys(tokens.space).map((k) => `  --spacing-${k}: var(--space-${k});`),
    ...Object.entries(tokens.radius).map(([k, v]) => `  --radius-${k}: ${v};`),
    ...Object.entries(tokens.font).map(([k, v]) => `  --font-${k}: ${v};`)
  ];
  return `/* GENERATED by packages/tokens/build.mjs from src/tokens.json — do not edit. */
@theme inline {
${lines.join("\n")}
}
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const tokens = JSON.parse(readFileSync(join(here, "src/tokens.json"), "utf8"));
  const outputs = [
    [join(here, "dist/tokens.css"), buildCss(tokens)],
    [join(here, "src/theme.css"), buildTheme(tokens)]
  ];
  for (const [out, css] of outputs) {
    if (process.argv.includes("--check")) {
      const cur = readFileSync(out, "utf8").replace(/\r\n/g, "\n");
      if (cur !== css) {
        console.error(`${out} is stale; run \`node packages/tokens/build.mjs\``);
        process.exit(1);
      }
    } else {
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, css);
    }
  }
}
